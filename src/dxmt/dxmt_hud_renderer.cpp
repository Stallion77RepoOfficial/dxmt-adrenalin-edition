HudRenderer::HudRenderer(WMT::Device device, InternalCommandLibrary &lib) : device_(device), lib_(lib) {
  buildFontTexture();

  WMTBufferInfo info;
  info.memory.set(0);
  info.length = kSliceBytes * kSliceCount;
  info.options = WMTResourceStorageModeShared;
  vbuf_ = device_.newBuffer(info);
  vbuf_mem_ = info.memory.get_accessible_or_null();

  dll_line_ = DetectLoadedDlls();
}

void
HudRenderer::buildFontTexture() {
  WMTTextureInfo info;
  info.type = WMTTextureType2D;
  info.pixel_format = WMTPixelFormatR8Unorm;
  info.usage = WMTTextureUsageShaderRead;
  info.options = WMTResourceStorageModeShared;
  info.width = kAtlasWidth;
  info.height = kAtlasHeight;
  info.depth = 1;
  info.mipmap_level_count = 1;
  info.sample_count = 1;
  info.array_length = 1;
  font_ = device_.newTexture(info);

  std::vector<uint8_t> atlas(kAtlasWidth * kAtlasHeight, 0);
  for (uint32_t g = 0; g < 96; g++) {
    uint32_t cx = (g % 16) * 8, cy = (g / 16) * 8;
    for (uint32_t row = 0; row < 8; row++) {
      uint8_t bits = kFont8x8[g][row];
      for (uint32_t col = 0; col < 8; col++)
        if (bits & (1u << col))
          atlas[(cy + row) * kAtlasWidth + cx + col] = 0xFF;
    }
  }
  font_.replaceRegion({0, 0, 0}, {kAtlasWidth, kAtlasHeight, 1}, 0, 0, atlas.data(), kAtlasWidth, 0);
}

bool
HudRenderer::ensurePipeline(WMTPixelFormat format) {
  if (pso_ && pso_format_ == format)
    return true;

  auto pool = WMT::MakeAutoreleasePool();
  auto library = lib_.getLibrary();
  auto vs = library.newFunction("vs_hud");
  auto fs = library.newFunction("fs_hud");

  WMTRenderPipelineInfo info;
  WMT::InitializeRenderPipelineInfo(info);
  info.vertex_function = vs;
  info.fragment_function = fs;
  info.colors[0].pixel_format = format;
  info.colors[0].blending_enabled = true;
  // Premultiplied-alpha over.
  info.colors[0].src_rgb_blend_factor = WMTBlendFactorOne;
  info.colors[0].dst_rgb_blend_factor = WMTBlendFactorOneMinusSourceAlpha;
  info.colors[0].src_alpha_blend_factor = WMTBlendFactorOne;
  info.colors[0].dst_alpha_blend_factor = WMTBlendFactorOneMinusSourceAlpha;

  WMT::Reference<WMT::Error> error;
  pso_ = device_.newRenderPipelineState(info, error);
  if (!pso_) {
    ERR("HUD: failed to create overlay pipeline state");
    return false;
  }
  pso_format_ = format;
  return true;
}

void
HudRenderer::quad(float x, float y, float w, float h, float u0, float v0, float u1, float v1, uint32_t color) {
  float x0 = (float)(x / width_ * 2.0 - 1.0);
  float x1 = (float)((x + w) / width_ * 2.0 - 1.0);
  float y0 = (float)(1.0 - y / height_ * 2.0);
  float y1 = (float)(1.0 - (y + h) / height_ * 2.0);
  Vertex a = {x0, y0, u0, v0, color};
  Vertex b = {x1, y0, u1, v0, color};
  Vertex c = {x0, y1, u0, v1, color};
  Vertex d = {x1, y1, u1, v1, color};
  verts_.push_back(a);
  verts_.push_back(b);
  verts_.push_back(c);
  verts_.push_back(c);
  verts_.push_back(b);
  verts_.push_back(d);
}

void
HudRenderer::fill(float x, float y, float w, float h, uint32_t color) {
  quad(x, y, w, h, -1.0f, 0.0f, -1.0f, 0.0f, color);
}

void
HudRenderer::text(float x, float y, float scale, uint32_t color, const std::string &str) {
  float pen = x;
  for (char ch : str) {
    uint8_t c = (uint8_t)ch;
    if (c < 0x20 || c > 0x7F) c = '?';
    uint32_t g = c - 0x20;
    float u = (float)((g % 16) * 8);
    float v = (float)((g / 16) * 8);
    if (c != ' ')
      quad(pen, y, kGlyphW * scale, kGlyphH * scale, u, v, u + 8.0f, v + 8.0f, color);
    pen += kGlyphW * scale;
  }
}

void
HudRenderer::encode(WMT::RenderCommandEncoder encoder, WMTPixelFormat format, double width, double height) {
  auto now = std::chrono::steady_clock::now();
  if (last_frame_.time_since_epoch().count() != 0) {
    float ms = std::chrono::duration<float, std::milli>(now - last_frame_).count();
    frame_times_[frame_cursor_ % kFrameHistory] = std::min(ms, 999.0f);
    frame_cursor_++;
  }
  last_frame_ = now;

  std::string heading;
  std::vector<std::string> stat_lines;
  {
    auto &contents = GetHudContents();
    std::lock_guard<std::mutex> lock(contents.mutex);
    if (!contents.active)
      return;
    heading = contents.heading;
    stat_lines = contents.lines;
  }
  if (!ensurePipeline(format))
    return;

  width_ = width;
  height_ = height;
  verts_.clear();

  // --- compose lines -----------------------------------------------------------
  uint32_t samples = std::min(frame_cursor_, kFrameHistory);
  float sum = 0, mn = 1e9f, mx = 0;
  for (uint32_t i = 0; i < samples; i++) {
    float t = frame_times_[i];
    sum += t;
    mn = std::min(mn, t);
    mx = std::max(mx, t);
  }
  float avg = samples ? sum / samples : 0;
  float fps = avg > 0 ? 1000.0f / avg : 0;

  std::vector<std::pair<std::string, uint32_t>> lines;
  if (!heading.empty())
    lines.push_back({heading, kColorHeading});
  lines.push_back({dll_line_, kColorText});
  if (samples) {
    lines.push_back({std::format("FPS: {:5.1f}", fps), kColorText});
    lines.push_back({std::format("Frame: {:5.2f}ms ({:4.2f}-{:5.2f})", avg, samples ? mn : 0.0f, mx), kColorText});
  }
  for (auto &l : stat_lines)
    lines.push_back({l, kColorText});

  float scale = height >= 1600 ? 2.0f : height >= 800 ? 1.5f : 1.0f;
  float pad = 8.0f * scale;
  float line_h = (kGlyphH + 2.0f) * scale;
  size_t max_chars = 16;
  for (auto &l : lines)
    max_chars = std::max(max_chars, l.first.size());

  float graph_h = 40.0f * scale;
  float panel_w = max_chars * kGlyphW * scale + pad * 2.0f;
  float panel_h = lines.size() * line_h + graph_h + pad * 3.0f;
  float panel_x = (float)width - panel_w - 10.0f * scale;
  float panel_y = 10.0f * scale;

  fill(panel_x, panel_y, panel_w, panel_h, kColorBackground);

  float ty = panel_y + pad;
  for (auto &l : lines) {
    text(panel_x + pad, ty, scale, l.second, l.first);
    ty += line_h;
  }

  // --- frame-time graph ----------------------------------------------------------
  float gx = panel_x + pad, gy = ty + pad, gw = panel_w - pad * 2.0f;
  fill(gx, gy, gw, graph_h, kColorGraphBg);
  if (samples) {
    float bar_w = gw / kFrameHistory;
    constexpr float kGraphMaxMs = 33.3f;
    for (uint32_t i = 0; i < samples; i++) {
      // Oldest to the left, newest at the right edge.
      uint32_t idx = (frame_cursor_ + kFrameHistory - samples + i) % kFrameHistory;
      float t = frame_times_[idx];
      float hgt = std::min(t / kGraphMaxMs, 1.0f) * graph_h;
      uint32_t color = t <= 17.0f ? kColorGood : t <= 33.3f ? kColorWarn : kColorBad;
      fill(gx + i * bar_w, gy + graph_h - hgt, std::max(bar_w - 1.0f, 1.0f), hgt, color);
    }
    // 16.7ms guide line.
    fill(gx, gy + graph_h * (1.0f - 16.7f / kGraphMaxMs), gw, 1.0f, PackColor(255, 255, 255, 90));
  }

  // --- submit ---------------------------------------------------------------------
  size_t bytes = verts_.size() * sizeof(Vertex);
  if (bytes == 0)
    return;
  if (bytes > kSliceBytes) {
    verts_.resize(kSliceBytes / sizeof(Vertex));
    bytes = verts_.size() * sizeof(Vertex);
  }
  uint32_t slice = slice_++ % kSliceCount;
  uint64_t offset = slice * kSliceBytes;
  if (vbuf_mem_)
    memcpy((uint8_t *)vbuf_mem_ + offset, verts_.data(), bytes);
  else
    vbuf_.updateContents(offset, verts_.data(), bytes);
  vbuf_.didModifyRange(offset, bytes);

  encoder.setRenderPipelineState(pso_);
  encoder.setVertexBuffer(vbuf_, offset, 0);
  encoder.setFragmentTexture(font_, 0);
  encoder.drawPrimitives(WMTPrimitiveTypeTriangle, 0, verts_.size());
}


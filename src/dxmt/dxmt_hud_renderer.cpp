constexpr uint32_t kAtlasWidth = 128;  // 16 glyphs per row
constexpr uint32_t kAtlasHeight = 48;  // 6 rows of glyphs
constexpr float kGlyphW = 8.0f;
constexpr float kGlyphH = 8.0f;

constexpr uint32_t kColorText = 0xFFFFFFFF;      // white
constexpr uint32_t kColorHeading = 0xFF00D7FF;   // gold-ish (R=255 G=215 B=0? packed R|G<<8|B<<16 -> 0xFF00D7FF = R 255, G 215, B 0, A 255)
constexpr uint32_t kColorBackground = 0xB4101010;
constexpr uint32_t kColorGraphBg = 0x96000000;
constexpr uint32_t kColorGood = 0xFF40C040;    // green (R64,G192,B64)
constexpr uint32_t kColorWarn = 0xFF30C0F0;    // amber-ish (R240,G192,B48)
constexpr uint32_t kColorBad = 0xFF3030E0;     // red (R224,G48,B48)

uint32_t
PackColor(uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
  return (uint32_t)r | ((uint32_t)g << 8) | ((uint32_t)b << 16) | ((uint32_t)a << 24);
}

std::string
DetectLoadedDlls() {
  static const wchar_t *kCandidates[] = {
    L"d3d8.dll", L"d3d9.dll", L"d3d10core.dll", L"d3d11.dll", L"dxgi.dll", L"winemetal.dll",
  };
  static const char *kNames[] = {"d3d8", "d3d9", "d3d10core", "d3d11", "dxgi", "winemetal"};
  std::string out = "DLL:";
  for (size_t i = 0; i < std::size(kCandidates); i++) {
    if (GetModuleHandleW(kCandidates[i])) {
      out += ' ';
      out += kNames[i];
    }
  }
  return out;
}


#pragma once

#include "d3d9caps.h"

namespace dxmt {

// Returns a D3DCAPS9 that accurately reflects what DXMT can deliver
// on top of a Metal/D3D11 backend.  We advertise SM3 (ps_3_0 / vs_3_0)
// because that is the highest D3D9 shader model we implement.
inline void
FillD3D9Caps(D3DCAPS9 *caps) {
  memset(caps, 0, sizeof(*caps));

  caps->DeviceType     = D3DDEVTYPE_HAL;
  caps->AdapterOrdinal = D3DADAPTER_DEFAULT;

  caps->Caps  = 0;
  caps->Caps2 = D3DCAPS2_CANAUTOGENMIPMAP | D3DCAPS2_DYNAMICTEXTURES | D3DCAPS2_FULLSCREENGAMMA;
  caps->Caps3 = D3DCAPS3_ALPHA_FULLSCREEN_FLIP_OR_DISCARD | D3DCAPS3_COPY_TO_VIDMEM | D3DCAPS3_COPY_TO_SYSTEMMEM | D3DCAPS3_LINEAR_TO_SRGB_PRESENTATION;

  caps->PresentationIntervals =
      D3DPRESENT_INTERVAL_IMMEDIATE | D3DPRESENT_INTERVAL_ONE |
      D3DPRESENT_INTERVAL_TWO       | D3DPRESENT_INTERVAL_THREE |
      D3DPRESENT_INTERVAL_FOUR;

  caps->CursorCaps = D3DCURSORCAPS_COLOR;

  caps->DevCaps =
      D3DDEVCAPS_CANBLTSYSTONONLOCAL | D3DDEVCAPS_CANRENDERAFTERFLIP |
      D3DDEVCAPS_DRAWPRIMTLVERTEX    | D3DDEVCAPS_EXECUTESYSTEMMEMORY |
      D3DDEVCAPS_EXECUTEVIDEOMEMORY  | D3DDEVCAPS_HWRASTERIZATION     |
      D3DDEVCAPS_HWTRANSFORMANDLIGHT | D3DDEVCAPS_PUREDEVICE          |
      D3DDEVCAPS_TEXTUREVIDEOMEMORY  | D3DDEVCAPS_TLVERTEXSYSTEMMEMORY|
      D3DDEVCAPS_TLVERTEXVIDEOMEMORY |
      // Required by the IW (Call of Duty) engine's "DirectX 7 compliant" check.
      D3DDEVCAPS_DRAWPRIMITIVES2      | D3DDEVCAPS_DRAWPRIMITIVES2EX;

  caps->PrimitiveMiscCaps =
      D3DPMISCCAPS_BLENDOP            | D3DPMISCCAPS_CLIPPLANESCALEDPOINTS  |
      D3DPMISCCAPS_CLIPTLVERTS        | D3DPMISCCAPS_COLORWRITEENABLE       |
      D3DPMISCCAPS_CULLCCW            | D3DPMISCCAPS_CULLCW                 |
      D3DPMISCCAPS_CULLNONE           | D3DPMISCCAPS_FOGANDSPECULARALPHA    |
      D3DPMISCCAPS_MASKZ              | D3DPMISCCAPS_MRTINDEPENDENTBITDEPTHS|
      D3DPMISCCAPS_MRTPOSTPIXELSHADERBLENDING | D3DPMISCCAPS_SEPARATEALPHABLEND |
      D3DPMISCCAPS_INDEPENDENTWRITEMASKS;

  caps->RasterCaps =
      D3DPRASTERCAPS_ANISOTROPY       | D3DPRASTERCAPS_COLORPERSPECTIVE     |
      D3DPRASTERCAPS_DEPTHBIAS        | D3DPRASTERCAPS_FOGRANGE             |
      D3DPRASTERCAPS_FOGTABLE         | D3DPRASTERCAPS_FOGVERTEX            |
      D3DPRASTERCAPS_MIPMAPLODBIAS    | D3DPRASTERCAPS_MULTISAMPLE_TOGGLE   |
      D3DPRASTERCAPS_SCISSORTEST      | D3DPRASTERCAPS_SLOPESCALEDEPTHBIAS  |
      D3DPRASTERCAPS_WBUFFER          | D3DPRASTERCAPS_WFOG                 |
      D3DPRASTERCAPS_ZBUFFERLESSHSR   | D3DPRASTERCAPS_ZFOG                 |
      D3DPRASTERCAPS_ZTEST;

  caps->ZCmpCaps = caps->AlphaCmpCaps =
      D3DPCMPCAPS_ALWAYS   | D3DPCMPCAPS_EQUAL    | D3DPCMPCAPS_GREATER |
      D3DPCMPCAPS_GREATEREQUAL | D3DPCMPCAPS_LESS | D3DPCMPCAPS_LESSEQUAL |
      D3DPCMPCAPS_NEVER    | D3DPCMPCAPS_NOTEQUAL;

  caps->SrcBlendCaps = caps->DestBlendCaps =
      D3DPBLENDCAPS_BLENDFACTOR    | D3DPBLENDCAPS_BOTHINVSRCALPHA |
      D3DPBLENDCAPS_BOTHSRCALPHA   | D3DPBLENDCAPS_DESTALPHA       |
      D3DPBLENDCAPS_DESTCOLOR      | D3DPBLENDCAPS_INVDESTALPHA     |
      D3DPBLENDCAPS_INVDESTCOLOR   | D3DPBLENDCAPS_INVSRCALPHA      |
      D3DPBLENDCAPS_INVSRCCOLOR    | D3DPBLENDCAPS_ONE              |
      D3DPBLENDCAPS_SRCALPHA       | D3DPBLENDCAPS_SRCALPHASAT      |
      D3DPBLENDCAPS_SRCCOLOR       | D3DPBLENDCAPS_ZERO;

  caps->ShadeCaps =
      D3DPSHADECAPS_ALPHAGOURAUDBLEND | D3DPSHADECAPS_COLORGOURAUDRGB |
      D3DPSHADECAPS_FOGGOURAUD        | D3DPSHADECAPS_SPECULARGOURAUDRGB;

  caps->TextureCaps =
      D3DPTEXTURECAPS_ALPHA           | D3DPTEXTURECAPS_ALPHAPALETTE |
      D3DPTEXTURECAPS_CUBEMAP         | D3DPTEXTURECAPS_CUBEMAP_POW2 |
      D3DPTEXTURECAPS_MIPCUBEMAP      | D3DPTEXTURECAPS_MIPMAP       |
      D3DPTEXTURECAPS_MIPVOLUMEMAP    | D3DPTEXTURECAPS_NOPROJECTEDBUMPENV |
      D3DPTEXTURECAPS_PERSPECTIVE     | D3DPTEXTURECAPS_POW2         |
      // POW2 is set, so the engine requires NONPOW2CONDITIONAL to pass its check.
      D3DPTEXTURECAPS_NONPOW2CONDITIONAL |
      D3DPTEXTURECAPS_PROJECTED       | D3DPTEXTURECAPS_TEXREPEATNOTSCALEDBYSIZE |
      D3DPTEXTURECAPS_VOLUMEMAP       | D3DPTEXTURECAPS_VOLUMEMAP_POW2;

  caps->TextureFilterCaps = caps->CubeTextureFilterCaps = caps->VolumeTextureFilterCaps =
      D3DPTFILTERCAPS_MAGFLINEAR | D3DPTFILTERCAPS_MAGFPOINT      |
      D3DPTFILTERCAPS_MINFANISOTROPIC | D3DPTFILTERCAPS_MINFLINEAR |
      D3DPTFILTERCAPS_MINFPOINT  | D3DPTFILTERCAPS_MIPFLINEAR     |
      D3DPTFILTERCAPS_MIPFPOINT;

  caps->TextureAddressCaps = caps->VolumeTextureAddressCaps =
      D3DPTADDRESSCAPS_BORDER      | D3DPTADDRESSCAPS_CLAMP |
      D3DPTADDRESSCAPS_INDEPENDENTUV | D3DPTADDRESSCAPS_MIRROR |
      D3DPTADDRESSCAPS_MIRRORONCE  | D3DPTADDRESSCAPS_WRAP;

  caps->LineCaps =
      D3DLINECAPS_ALPHACMP | D3DLINECAPS_BLEND | D3DLINECAPS_FOG |
      D3DLINECAPS_TEXTURE  | D3DLINECAPS_ZTEST;

  caps->MaxTextureWidth  = 16384;
  caps->MaxTextureHeight = 16384;
  caps->MaxVolumeExtent  = 2048;
  caps->MaxTextureRepeat = 32768;
  caps->MaxTextureAspectRatio = 0; // no restriction
  caps->MaxAnisotropy    = 16;
  caps->MaxVertexW       = 1e10f;

  caps->GuardBandLeft   = -32768.0f;
  caps->GuardBandTop    = -32768.0f;
  caps->GuardBandRight  =  32768.0f;
  caps->GuardBandBottom =  32768.0f;

  caps->ExtentsAdjust = 0.0f;

  caps->StencilCaps =
      D3DSTENCILCAPS_DECR     | D3DSTENCILCAPS_DECRSAT |
      D3DSTENCILCAPS_INCR     | D3DSTENCILCAPS_INCRSAT |
      D3DSTENCILCAPS_INVERT   | D3DSTENCILCAPS_KEEP    |
      D3DSTENCILCAPS_REPLACE  | D3DSTENCILCAPS_ZERO    |
      D3DSTENCILCAPS_TWOSIDED;

  caps->FVFCaps =
      D3DFVFCAPS_PSIZE | (8 << D3DFVFCAPS_TEXCOORDCOUNTMASK);

  caps->TextureOpCaps =
      D3DTEXOPCAPS_ADD                | D3DTEXOPCAPS_ADDSIGNED         |
      D3DTEXOPCAPS_ADDSIGNED2X        | D3DTEXOPCAPS_ADDSMOOTH         |
      D3DTEXOPCAPS_BLENDCURRENTALPHA  | D3DTEXOPCAPS_BLENDDIFFUSEALPHA |
      D3DTEXOPCAPS_BLENDFACTORALPHA   | D3DTEXOPCAPS_BLENDTEXTUREALPHA |
      D3DTEXOPCAPS_BLENDTEXTUREALPHAPM| D3DTEXOPCAPS_BUMPENVMAP        |
      D3DTEXOPCAPS_BUMPENVMAPLUMINANCE| D3DTEXOPCAPS_DISABLE           |
      D3DTEXOPCAPS_DOTPRODUCT3        | D3DTEXOPCAPS_LERP              |
      D3DTEXOPCAPS_MODULATE           | D3DTEXOPCAPS_MODULATE2X        |
      D3DTEXOPCAPS_MODULATE4X         | D3DTEXOPCAPS_MODULATEALPHA_ADDCOLOR |
      D3DTEXOPCAPS_MODULATECOLOR_ADDALPHA | D3DTEXOPCAPS_MODULATEINVALPHA_ADDCOLOR |
      D3DTEXOPCAPS_MODULATEINVCOLOR_ADDALPHA | D3DTEXOPCAPS_MULTIPLYADD |
      D3DTEXOPCAPS_PREMODULATE        | D3DTEXOPCAPS_SELECTARG1        |
      D3DTEXOPCAPS_SELECTARG2         | D3DTEXOPCAPS_SUBTRACT;

  caps->MaxTextureBlendStages   = 8;
  caps->MaxSimultaneousTextures = 8;

  caps->VertexProcessingCaps =
      D3DVTXPCAPS_DIRECTIONALLIGHTS    | D3DVTXPCAPS_LOCALVIEWER |
      D3DVTXPCAPS_MATERIALSOURCE7      |
      D3DVTXPCAPS_POSITIONALLIGHTS     | D3DVTXPCAPS_TEXGEN |
      D3DVTXPCAPS_TEXGEN_SPHEREMAP;

  caps->MaxActiveLights             = 8;
  caps->MaxUserClipPlanes           = 8;
  caps->MaxVertexBlendMatrices      = 4;
  caps->MaxVertexBlendMatrixIndex   = 255;
  caps->MaxPointSize                = 256.0f;
  caps->MaxPrimitiveCount           = 0x555555;
  caps->MaxVertexIndex              = 0xFFFFFF;
  caps->MaxStreams                  = 16;
  caps->MaxStreamStride             = 508;

  // Shader model 3.0
  caps->VertexShaderVersion          = D3DVS_VERSION(3, 0);
  caps->MaxVertexShaderConst         = 256;
  caps->PixelShaderVersion           = D3DPS_VERSION(3, 0);
  caps->PixelShader1xMaxValue        = 8.0f;

  caps->DevCaps2 =
      D3DDEVCAPS2_ADAPTIVETESSRTPATCH | D3DDEVCAPS2_ADAPTIVETESSNPATCH |
      D3DDEVCAPS2_CAN_STRETCHRECT_FROM_TEXTURES |
      D3DDEVCAPS2_DMAPNPATCH | D3DDEVCAPS2_PRESAMPLEDDMAPNPATCH |
      D3DDEVCAPS2_STREAMOFFSET | D3DDEVCAPS2_VERTEXELEMENTSCANSHARESTREAMOFFSET;

  caps->MaxNpatchTessellationLevel = 0.0f;
  caps->MasterAdapterOrdinal       = 0;
  caps->AdapterOrdinalInGroup      = 0;
  caps->NumberOfAdaptersInGroup    = 1;

  caps->DeclTypes =
      D3DDTCAPS_UBYTE4    | D3DDTCAPS_UBYTE4N  | D3DDTCAPS_SHORT2N |
      D3DDTCAPS_SHORT4N   | D3DDTCAPS_USHORT2N | D3DDTCAPS_USHORT4N|
      D3DDTCAPS_UDEC3     | D3DDTCAPS_DEC3N    | D3DDTCAPS_FLOAT16_2|
      D3DDTCAPS_FLOAT16_4;

  caps->NumSimultaneousRTs = 4;

  caps->StretchRectFilterCaps =
      D3DPTFILTERCAPS_MINFLINEAR | D3DPTFILTERCAPS_MINFPOINT |
      D3DPTFILTERCAPS_MAGFLINEAR | D3DPTFILTERCAPS_MAGFPOINT;

  caps->VS20Caps.Caps                  = D3DVS20CAPS_PREDICATION;
  caps->VS20Caps.DynamicFlowControlDepth = D3DVS20_MAX_DYNAMICFLOWCONTROLDEPTH;
  caps->VS20Caps.NumTemps              = D3DVS20_MAX_NUMTEMPS;
  caps->VS20Caps.StaticFlowControlDepth = D3DVS20_MAX_STATICFLOWCONTROLDEPTH;

  caps->PS20Caps.Caps                  = D3DPS20CAPS_ARBITRARYSWIZZLE |
                                         D3DPS20CAPS_GRADIENTINSTRUCTIONS |
                                         D3DPS20CAPS_NODEPENDENTREADLIMIT |
                                         D3DPS20CAPS_NOTEXINSTRUCTIONLIMIT |
                                         D3DPS20CAPS_PREDICATION;
  caps->PS20Caps.DynamicFlowControlDepth = D3DPS20_MAX_DYNAMICFLOWCONTROLDEPTH;
  caps->PS20Caps.NumTemps              = D3DPS20_MAX_NUMTEMPS;
  caps->PS20Caps.StaticFlowControlDepth = D3DPS20_MAX_STATICFLOWCONTROLDEPTH;
  caps->PS20Caps.NumInstructionSlots   = D3DPS20_MAX_NUMINSTRUCTIONSLOTS;

  caps->VertexTextureFilterCaps        = caps->TextureFilterCaps;
  caps->MaxVShaderInstructionsExecuted = 65535;
  caps->MaxPShaderInstructionsExecuted = 65535;
  caps->MaxVertexShader30InstructionSlots = 32768;
  caps->MaxPixelShader30InstructionSlots  = 32768;
}

} // namespace dxmt
